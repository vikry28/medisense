import { createHmac } from "node:crypto";
import { DeviceStatus, PrismaClient } from "@prisma/client";
import { hashPassword } from "../src/common/utils/password";

const prisma = new PrismaClient();

const DEMO_EMAIL = process.env.SEED_DEMO_EMAIL ?? "demo@medisense.local";
const DEMO_PASSWORD = process.env.SEED_DEMO_PASSWORD ?? "Demo1234!";
const PAIRING_CODE = process.env.SEED_DEVICE_PAIRING_CODE ?? "123456";
const PAIRING_PEPPER =
  process.env.PAIRING_CODE_PEPPER ?? "dev-pairing-pepper-change-me";

function pairingHash(deviceCode: string, code: string): string {
  return createHmac("sha256", PAIRING_PEPPER)
    .update(`${deviceCode}:${code}`)
    .digest("hex");
}

async function main(): Promise<void> {
  const passwordHash = await hashPassword(DEMO_PASSWORD);

  const user = await prisma.user.upsert({
    where: { email: DEMO_EMAIL },
    update: { name: "Demo User", passwordHash, emailVerifiedAt: new Date() },
    create: {
      name: "Demo User",
      email: DEMO_EMAIL,
      passwordHash,
      emailVerifiedAt: new Date(),
    },
  });

  await prisma.alertConfig.createMany({
    data: [
      {
        userId: user.id,
        parameter: "HEART_RATE",
        minValue: 50,
        maxValue: 100,
        enabled: true,
      },
      {
        userId: user.id,
        parameter: "SPO2",
        minValue: 95,
        maxValue: 100,
        enabled: true,
      },
      {
        userId: user.id,
        parameter: "TEMPERATURE",
        minValue: 36.1,
        maxValue: 37.5,
        enabled: true,
      },
    ],
    skipDuplicates: true,
  });

  const simulatorDevice = await prisma.device.upsert({
    where: { deviceCode: "ESP32-001" },
    update: {
      name: "Demo Sensor 001",
      type: "ESP32",
    },
    create: {
      deviceCode: "ESP32-001",
      name: "Demo Sensor 001",
      type: "ESP32",
      status: DeviceStatus.OFFLINE,
    },
  });

  const activeAssignment = await prisma.deviceAssignment.findFirst({
    where: { deviceId: simulatorDevice.id, unassignedAt: null },
  });
  if (!activeAssignment) {
    const previousAssignment = await prisma.deviceAssignment.findFirst({
      where: { deviceId: simulatorDevice.id, userId: user.id },
    });
    if (previousAssignment) {
      await prisma.deviceAssignment.update({
        where: { id: previousAssignment.id },
        data: { unassignedAt: null },
      });
    } else {
      await prisma.deviceAssignment.create({
        data: { deviceId: simulatorDevice.id, userId: user.id },
      });
    }
  }

  const pairingDevice = await prisma.device.upsert({
    where: { deviceCode: "ESP32-002" },
    update: {},
    create: {
      deviceCode: "ESP32-002",
      name: "Demo Sensor 002",
      type: "ESP32",
      status: DeviceStatus.OFFLINE,
    },
  });

  const pairingDeviceAssignment = await prisma.deviceAssignment.findFirst({
    where: { deviceId: pairingDevice.id, unassignedAt: null },
  });
  if (!pairingDeviceAssignment) {
    await prisma.device.update({
      where: { id: pairingDevice.id },
      data: {
        pairingCodeHash: pairingHash(pairingDevice.deviceCode, PAIRING_CODE),
        pairingCodeExpiresAt: new Date(Date.now() + 30 * 24 * 60 * 60 * 1000),
      },
    });
  }

  console.log("");
  console.log("MediSense seed complete");
  console.log("-----------------------");
  console.log(`User:        ${DEMO_EMAIL}`);
  console.log(`Password:    ${DEMO_PASSWORD}`);
  console.log(`Simulator:   ESP32-001 (already paired with demo user)`);
  console.log(
    `Pairing demo: ESP32-002 / pairing code ${PAIRING_CODE} (valid 30 days)`,
  );
  console.log("");
  console.log("MQTT development credentials are generated by the");
  console.log("mosquitto-init service in infrastructure/docker-compose.yml.");
  console.log("");
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
